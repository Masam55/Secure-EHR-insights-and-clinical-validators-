CREATE TABLE IF NOT EXISTS patient_encounters(
    id SERIAL PRIMARY KEY,
    subject_id BIGINT,
    hadm_id BIGINT,
    admission_type VARCHAR(100),
    admission_location VARCHAR(100),
    discharge_location VARCHAR(100),
    insurance VARCHAR(100),
    marital_status VARCHAR(100),
    race VARCHAR(100),
    gender VARCHAR(10),
    anchor_age INT,
    drug VARCHAR(100),
    formular_drug_cd VARCHAR(100),
    prod_strength VARCHAR(100),
    dose_val_rx VARCHAR(100),
    dose_unit_rx VARCHAR(100),
    form_unit_disp VARCHAR(100),
    route VARCHAR(50),
    event_type VARCHAR(100),
    careunit VARCHAR(100),
    order_type VARCHAR(100),
    order_subtype VARCHAR(100),
    transaction_type VARCHAR(100),
    spec_type_desc VARCHAR(100),
    test_name VARCHAR(150),
    org_name VARCHAR(150),
    ab_name VARCHAR(150),
    comment TEXT,
    drg_type VARCHAR(150),
    description TEXT,
    drg_severity VARCHAR(50),
    drg_mortality VARCHAR(50)
    );